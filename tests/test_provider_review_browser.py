"""Opt-in rendered recorder/review rehearsal with the actual receiver and PostgreSQL.

The capture is generated by the retained encrypted-protocol fixture before mount.
The already-uploaded recorder host, identity, native bridge and Core entry are
fixtures. This is not native capture, hosted sign-in or live provider acceptance.
"""

from __future__ import annotations

import asyncio
import json
import os
import socket
from pathlib import Path
from uuid import uuid4

import pytest
import uvicorn
from cosmaneura_scribe.creator_review_routes import CreatorReviewRuntime
from cosmaneura_scribe.main import app
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from starlette.applications import Starlette
from starlette.requests import Request
from starlette.responses import FileResponse, HTMLResponse, JSONResponse, Response
from starlette.routing import Route
from test_captured_processing import Flow
from test_captured_processing import flow as flow
from test_captured_source_runtime import trial as trial
from test_captured_transcription_worker import capture as capture

pytestmark = [pytest.mark.postgres, pytest.mark.asyncio]
ROOT = Path(__file__).resolve().parents[1]


@pytest.mark.skipif(os.getenv("SCRIBE_BROWSER_TRIAL") != "1", reason="explicit local browser trial")
@pytest.mark.parametrize("decision", ["accepted", "rejected"])
async def test_rendered_provider_review(flow: Flow, tmp_path: Path, decision: str):
    await flow.capture.record()
    runtime = CreatorReviewRuntime(
        flow.capture.trial.provider, tenant_ids=frozenset({flow.capture.trial.tenant}), enabled=True
    )
    app.state.creator_review_runtime = runtime
    session_id, scope = str(flow.capture.trial.draft.id), str(uuid4())
    pending_path = tmp_path / "encrypted-native-bridge-fixture.bin"
    cipher = AESGCM(AESGCM.generate_key(bit_length=256))
    requests: list[tuple[str, dict]] = []

    async def review(request: Request):
        headers = {"X-Scribe-Creator-Actor-ID": flow.capture.trial.draft.creator_actor_id}
        path = f"/v1/captured-sessions/{session_id}/review"
        if request.method == "POST":
            body = await request.json()
            key = request.headers["idempotency-key"]
            requests.append((key, body))
            headers["Idempotency-Key"] = key
            response = await flow.capture.client.post(path, json=body, headers=headers)
            if len(requests) == 1:
                assert response.status_code == 200
                return Response(status_code=503)  # committed response is lost
        else:
            response = await flow.capture.client.get(path, headers=headers)
        return Response(response.content, status_code=response.status_code,
                        media_type="application/json", headers={"Cache-Control": "no-store"})

    async def process(_request: Request):
        await flow.runtime.process(**flow.scope)
        return JSONResponse({"processed": True})

    async def revoke(_request: Request):
        async with flow.capture.trial.provider.transaction(flow.capture.trial.tenant) as store:
            await store.revoke_consent(flow.capture.trial.tenant, flow.capture.trial.consent.id)
        return JSONResponse({"revoked": True})

    async def journal(request: Request):
        command = await request.json()
        current = None
        if pending_path.exists():
            encoded = pending_path.read_bytes()
            current = json.loads(cipher.decrypt(encoded[:12], encoded[12:], scope.encode()))
        if command["method"] == "get":
            return JSONResponse(current or {"code": "SECURE_QUEUE_NOT_FOUND"},
                                status_code=200 if current else 404)
        value = command["value"]
        if (command["method"] == "create" and current is not None) or (
            command["method"] == "compareAndSwap" and (
                current is None or value["expectedRevision"] != current["revision"]
            )
        ):
            return JSONResponse({"code": "SECURE_QUEUE_REVISION_CONFLICT"}, status_code=409)
        stored = {"key": value["key"], "data": value["data"],
                  "revision": str(int(current["revision"]) + 1) if current else "1"}
        nonce = os.urandom(12)
        pending_path.write_bytes(
            nonce + cipher.encrypt(nonce, json.dumps(stored).encode(), scope.encode())
        )
        return JSONResponse({"revision": stored["revision"]})

    async def index(_request: Request):
        return HTMLResponse(_page(session_id, scope), headers={"Cache-Control": "no-store"})

    async def asset(request: Request):
        name = request.path_params["name"]
        if name not in {"provider-capture.js", "provider-capture.css"}:
            return Response(status_code=404)
        return FileResponse(ROOT / "apps/capture/dist/provider" / name)

    application = Starlette(routes=[
        Route("/", index), Route("/assets/{name}", asset),
        Route(f"/v1/captured-sessions/{session_id}/review", review, methods=["GET", "POST"]),
        Route("/trial/process", process, methods=["POST"]),
        Route("/trial/revoke", revoke, methods=["POST"]),
        Route("/trial/journal", journal, methods=["POST"]),
    ])
    listener = socket.socket()
    listener.bind(("127.0.0.1", 0))
    server = uvicorn.Server(uvicorn.Config(application, log_level="critical", access_log=False))
    task = asyncio.create_task(server.serve(sockets=[listener]))
    result = None
    try:
        for _ in range(100):
            if server.started:
                break
            await asyncio.sleep(0.01)
        assert server.started
        result = await asyncio.create_subprocess_exec(
            os.environ["SCRIBE_NODE"], str(ROOT / "tests/browser/provider-review.mjs"),
            f"http://127.0.0.1:{listener.getsockname()[1]}", decision, str(tmp_path),
            stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
        )
        stdout, stderr = await asyncio.wait_for(result.communicate(), timeout=90)
        assert result.returncode == 0, stderr.decode()[-4000:]
        assert json.loads(stdout)["reload_recovered"]
        assert len(requests) == 2 and requests[0] == requests[1]
        assert await flow.counts() == (1, 1, 1)
        assert flow.capture.speech.calls == 1 and len(flow.translator.calls) == 1
    finally:
        if result is not None and result.returncode is None:
            result.kill()
            await result.wait()
        server.should_exit = True
        await task
        listener.close()
        del app.state.creator_review_runtime


def _page(session: str, scope: str) -> str:
    # All identifiers/data are generated local fixtures; no auth or native token is supplied.
    template = (ROOT / "tests/browser/provider-review.html").read_text()
    return template.replace("SESSION", json.dumps(session)).replace("SCOPE", json.dumps(scope))

"""Native-only source-start intent; Core supplies creator and tenant separately."""

from __future__ import annotations

import hashlib
import json
import re
from typing import Literal
from uuid import UUID

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    SecretStr,
    SerializerFunctionWrapHandler,
    field_validator,
    model_serializer,
)

SourceKind = Literal["desktop_companion", "ios_microphone"]
StartAction = Literal["prepare", "authorize", "cancel", "stop"]


class SourceStartIntent(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, hide_input_in_errors=True)

    schema_version: Literal["1.0"] = "1.0"
    attempt_id: UUID
    source: SourceKind
    # 32 random bytes generated by the native owner. The proposed native-only
    # protected journal retains stop custody; never a renderer argument or token.
    owner_proof: SecretStr = Field(repr=False)
    lease_id: UUID
    lease_receipt_id: UUID
    lease_generation: int = Field(strict=True, ge=1)
    capture_authorized_until: AwareDatetime
    first_sequence_number: int = Field(default=0, strict=True, ge=0, le=999)

    @model_serializer(mode="wrap")
    def compatible_position(self, handler: SerializerFunctionWrapHandler):
        value = handler(self)
        if self.first_sequence_number == 0:
            value.pop("first_sequence_number", None)
        return value

    @field_validator("owner_proof")
    @classmethod
    def proof_format(cls, value: SecretStr) -> SecretStr:
        if re.fullmatch(r"[0-9a-f]{64}", value.get_secret_value()) is None:
            raise ValueError("native owner proof is invalid")
        return value

    @property
    def proof_digest(self) -> str:
        return hashlib.sha256(self.owner_proof.get_secret_value().encode("ascii")).hexdigest()

    def fingerprint(self, session_id: UUID, actor: str) -> str:
        # Bind the proof digest, never serialize the proof or its masked placeholder.
        data = self.model_dump(mode="json", exclude={"owner_proof"})
        data.update(
            session_id=str(session_id), creator_actor_id=actor, owner_proof_sha256=self.proof_digest
        )
        return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


class SourceStartReceipt(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, hide_input_in_errors=True)

    schema_version: Literal["1.0"] = "1.0"
    session_id: UUID
    attempt_id: UUID
    source_start_id: UUID
    creator_actor_id: str
    consent_record_id: UUID
    source: SourceKind
    lease_id: UUID
    lease_receipt_id: UUID
    lease_generation: int = Field(strict=True, ge=1)
    state: Literal["prepared", "issued", "cancelled", "expired", "stopped"]
    preparation_expires_at: AwareDatetime
    capture_authorized_until: AwareDatetime
    issued_at: AwareDatetime | None
    expires_at: AwareDatetime | None
    capability_id: UUID
    first_sequence_number: int = Field(default=0, strict=True, ge=0, le=999)

    @model_serializer(mode="wrap")
    def compatible_position(self, handler: SerializerFunctionWrapHandler):
        value = handler(self)
        if self.first_sequence_number == 0:
            value.pop("first_sequence_number", None)
        return value


class SourceStartCapability(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, hide_input_in_errors=True)

    receipt: SourceStartReceipt
    # SecretStr remains masked in ordinary JSON/repr. The route deliberately
    # unwraps it only for a successful authenticated native response.
    secret: SecretStr = Field(repr=False)


class SourceStartRetirementReceipt(BaseModel):
    """Terminal closure of an attempt which never became a prepared source."""
    model_config = ConfigDict(extra="forbid", frozen=True, hide_input_in_errors=True)

    schema_version: Literal["1.0"] = "1.0"
    state: Literal["unstarted"] = "unstarted"
    retirement_id: UUID
    session_id: UUID
    attempt_id: UUID
    creator_actor_id: str = Field(pattern=r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
    consent_record_id: UUID
    source: Literal["desktop_companion", "ios_microphone"]
    owner_proof_sha256: str = Field(pattern=r"^[0-9a-f]{64}$", repr=False)
    lease_id: UUID
    lease_receipt_id: UUID
    lease_generation: int = Field(strict=True, ge=1)
    capture_authorized_until: AwareDatetime
    first_sequence_number: int = Field(default=0, strict=True, ge=0, le=999)
    retired_at: AwareDatetime

    @model_serializer(mode="wrap")
    def compatible_position(self, handler: SerializerFunctionWrapHandler):
        value = handler(self)
        if self.first_sequence_number == 0:
            value.pop("first_sequence_number", None)
        return value

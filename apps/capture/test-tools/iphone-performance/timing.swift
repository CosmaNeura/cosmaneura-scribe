import Foundation
import CosmaneuraNativeRecording

// Physical input/source/SDK/network are fixture-owned. Actual host custody,
// prewarming, lease reuse, cancellation and PCM encryption run unchanged.
@main struct Timing {
  @MainActor static func main() async throws {
    var results: [[String: Any]] = []
    func ms(_ start: ContinuousClock.Instant) -> Double {
      let d = start.duration(to: .now).components
      return (Double(d.seconds) * 1000 + Double(d.attoseconds) / 1e15)
    }
    for name in ["cold", "prewarmed", "resume", "lease-delay-650", "lease-delay-4500", "cancel-held-lease", "service-failure"] {
      let f = try CheckNativeRecordingHost.Fixture()
      let host = f.host()
      let delayed = name.hasPrefix("lease-delay") || name == "cancel-held-lease"
      if delayed { await f.service.configure(hold: true) }

      let opening = ContinuousClock.now
      try await host.open()
      let openingMs = ms(opening)
      if name == "service-failure" { await f.service.configure(failAll: true) }
      if name == "prewarmed" { try await CheckNativeRecordingHost.wait { await f.service.reservations == 1 } }
      if name == "resume" {
        try await host.start(); try f.runs.last!.emit(); try await host.pause()
      }
      if delayed { try await CheckNativeRecordingHost.wait { await f.service.pending != nil } }
      let start = ContinuousClock.now
      var outcome = "synthetic-pcm-committed", completionMs: Double
      var phaseAt4s: String? = nil
      if name == "cancel-held-lease" {
        var settled = false
        let task = Task { do { try await host.start() } catch {} ; settled = true }
        try await CheckNativeRecordingHost.wait { host.phase == .starting }
        let cancel = ContinuousClock.now
        try await host.pause()
        try await CheckNativeRecordingHost.wait { settled && !host.busy }
        completionMs = ms(cancel)
        try CheckNativeRecordingHost.check(host.phase == .paused && f.runs.isEmpty)
        outcome = "cancel-confirmed-no-source"
        await f.service.release(); await task.value
      } else {
        if delayed {
          let injected = name == "lease-delay-650" ? 650 : 4500
          Task { try? await Task.sleep(for: .milliseconds(injected)); await f.service.release() }
          if injected > 4000 {
            Task { try? await Task.sleep(for: .milliseconds(4000)); phaseAt4s = String(describing: host.phase) }
          }
        }
        do {
          try await host.start()
          try CheckNativeRecordingHost.check(host.phase == .recording)
          // Generated bytes explicitly stand in for the driver's first packet.
          try f.runs.last!.emit()
          try CheckNativeRecordingHost.check(f.runs.last!.sink.state.committedChunks > 0)
          completionMs = ms(start)
        } catch {
          guard name == "service-failure" else { throw error }
          completionMs = ms(start); outcome = "actionable-start-failed"
        }
      }
      let intents = await f.service.leaseIntents
      let row: [String: Any] = ["scenario": name, "hostOpenMs": openingMs, "actionToResultMs": completionMs,
        "outcome": outcome, "phaseAt4s": phaseAt4s ?? "not-observed", "uniqueLeaseIntents": Set(intents).count,
        "leaseIssues": await f.service.issues, "sourceIntervals": f.runs.count,
        "successWithin4s": outcome == "synthetic-pcm-committed" && completionMs <= 4000]
      results.append(row)
      try await host.close()
    }
    let evidence: [String: Any] = ["runtime": "macOS-hosted Swift 6 optimized actual native recording host",
      "physicalIOS": false, "microphone": false, "network": false,
      "substitutions": "in-memory consent-authorized service/storage; ephemeral RSA wrapping key; generated PCM packet after synthetic start",
      "results": results]
    print(String(decoding: try JSONSerialization.data(withJSONObject: evidence, options: [.prettyPrinted, .sortedKeys]), as: UTF8.self))
  }
}

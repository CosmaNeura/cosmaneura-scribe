def _write_or_check(path: Path, value: str, *, check: bool) -> bool:
    if check:
        if not path.is_file() or path.read_text() != value:
            print(f"out of date: {path.relative_to(ROOT)}")
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value)
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec, source_sha256 = _load_spec()
    artifacts = {
        PYTHON_PATH: _python_source(spec, source_sha256),
        TYPESCRIPT_PATH: _typescript_source(spec, source_sha256),
        GOLDEN_PATH: _golden_vectors(spec, source_sha256),
    }
    current = all(
        _write_or_check(path, value, check=args.check) for path, value in artifacts.items()
    )
    return 0 if current else 1


